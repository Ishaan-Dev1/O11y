#!/bin/bash
# ==============================================================================
# Resource adoption script for otel-operator on LDC.
#
# Purpose: the current otel-operator deployment on LDC was applied via plain
# manifests (kubectl apply), NOT via a real `helm install`. Resources have the
# chart's LABELS but are missing Helm's OWNERSHIP ANNOTATIONS
# (meta.helm.sh/release-name, meta.helm.sh/release-namespace), which Helm
# requires before it will manage an existing resource under a new release.
#
# This script patches ONLY annotations/labels - it does NOT delete, restart,
# or modify the spec of any resource. Safe to run against live resources.
#
# Run this BEFORE `helm upgrade --install`:
#   cd Otel-operator && helm dependency update
#   helm upgrade --install otel-operator . -n observability
# ==============================================================================

set -euo pipefail

NS="observability"
RELEASE="otel-operator"

adopt() {
  local resource="$1"
  echo "Adopting ${resource} -> release ${RELEASE}"
  kubectl annotate "${resource}" -n "${NS}" \
    "meta.helm.sh/release-name=${RELEASE}" \
    "meta.helm.sh/release-namespace=${NS}" \
    --overwrite || echo "  (skip: ${resource} not found)"
  kubectl label "${resource}" -n "${NS}" \
    "app.kubernetes.io/managed-by=Helm" \
    --overwrite || true
}

echo "=== Adopting resources for release: ${RELEASE} (ns: ${NS}) ==="

# Workloads
adopt "deploy/otel-operator"

# ServiceAccount
adopt "sa/operator"

# RBAC
adopt "clusterrole/otel-operator-manager"
adopt "clusterrolebinding/otel-operator-manager"

# Webhooks
adopt "mutatingwebhookconfigurations/otel-operator-mutation"
adopt "validatingwebhookconfigurations/otel-operator-validation"

# Services (including webhook service)
adopt "svc/otel-operator"
adopt "svc/otel-operator-webhook"

# Secret (webhook certs)
adopt "secret/otel-operator-controller-manager-service-cert"

# Instrumentation CRs (deployed manually, need adoption for Helm)
adopt "instrumentation/coe-dev-otel-instrumentation"
adopt "instrumentation/coe-prod-otel-instrumentation"
adopt "instrumentation/otel-instrumentation"

# Deliberately NOT adopted:
#   - ReplicaSets/Pods/Endpoints (auto-generated by controllers)
#   - otel-collector resources (managed by operator, different names than chart)
#   - faro-otel / kube-event-otel resources (out of scope)

echo ""
echo "=== Adoption complete. Verify with: ==="
echo "kubectl get deploy otel-operator -n ${NS} -o jsonpath='{.metadata.annotations}'"
